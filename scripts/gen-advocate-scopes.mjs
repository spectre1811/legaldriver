#!/usr/bin/env node
// BP-57 / BP-05 W2 · Generate src/lib/court/advocate-scopes.data.ts.
//
// SOURCE OF TRUTH: the platform court-scope registry — HC + every district complex per state — is
// OWNED and SERVED by the platform at GET /v1/advocate-scopes?state_code=<int> (ecourts-scraper
// court.court_scope). This generator pulls that contract so the app's ADVOCATE_SCOPES is a build-time
// CONSUMER, never a hand-maintained copy that drifts (widening district coverage becomes a platform
// data row — the masters walk — not a code deploy here). It falls back per-state to the committed
// snapshot (advocate-scopes.source.json) when the platform is unreachable (offline builds), so a build
// never breaks. The output shape is exactly what bar-number.ts::barSearchScopes consumes.
//
// This REPLACES the single hardcoded district complex (dist_code=1, court_code_arr="1,5") that used to
// live in barSearchScopes with the full, data-driven scope list — the BP-57 "nothing missed" unblock.
// Until the founder-gated W2 masters walk populates court_scope statewide, the contract returns
// `coverage:"hc_only"` (or the fallback's one verified complex) and the app degrades HONESTLY.
//
// Run (contract, default): LD_API_BASE=http://13.202.148.71:8080 LD_API_KEY=… node scripts/gen-advocate-scopes.mjs
// Run (force offline):     node scripts/gen-advocate-scopes.mjs --source=json
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const SRC = join(root, "src/lib/court/advocate-scopes.source.json");
const OUT = join(root, "src/lib/court/advocate-scopes.data.ts");
const forceJson = process.argv.includes("--source=json");

// Map ONE platform/snapshot scope (snake_case, shared by both sources) → the app's AdvocateScopeRow.
// HC carries court_code=1 (one court); a DC complex carries court_code_arr (the njdg_est_code list).
const toRow = (s) => {
  const tier = s.tier === "DC" ? "DC" : "HC";
  const row = { tier };
  if (tier === "HC") {
    row.distCode = s.dist_code ?? 1;
    row.courtCode = 1;
  } else {
    if (s.dist_code != null) row.distCode = s.dist_code;
    if (s.court_code_arr != null) row.courtCodeArr = s.court_code_arr;
  }
  if (s.est_name != null) row.estName = s.est_name;
  return row;
};

// ── source: committed offline snapshot (defines which states we know + the fallback scopes) ──
const snapshot = JSON.parse(readFileSync(SRC, "utf8")).states;

// ── source: platform contract (BP-57 /v1/advocate-scopes?state_code=…), per state ──
async function fromContract(stateCode) {
  const base = process.env.LD_API_BASE, key = process.env.LD_API_KEY;
  if (forceJson || !base || !key) return null;
  try {
    const res = await fetch(`${base.replace(/\/$/, "")}/v1/advocate-scopes?state_code=${stateCode}`, {
      headers: { "X-API-Key": key }, signal: AbortSignal.timeout(30000),
    });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const body = await res.json();
    const scopes = body?.scopes;
    if (!Array.isArray(scopes) || !scopes.length) throw new Error("no scopes in contract response");
    return { scopes, coverage: body.coverage ?? "full", provenance: `contract (generated_at ${body.generated_at ?? "—"}, coverage ${body.coverage ?? "?"})` };
  } catch (e) {
    console.warn(`[gen-advocate-scopes] state ${stateCode}: contract fetch failed (${e.message}); using committed snapshot`);
    return null;
  }
}

// ── emit ─────────────────────────────────────────────────────────────────────
const scopesByState = {};
const coverageByState = {};
const provByState = {};
for (const [stateCode, entry] of Object.entries(snapshot)) {
  const live = await fromContract(stateCode);
  const src = live ?? { scopes: entry.scopes, coverage: entry.coverage ?? "unknown", provenance: "committed snapshot (advocate-scopes.source.json)" };
  scopesByState[stateCode] = src.scopes.map(toRow);
  coverageByState[stateCode] = src.coverage;
  provByState[stateCode] = `${entry.label ?? stateCode}: ${src.provenance}`;
}

const rowLit = (r) => "{ " + [
  `tier: ${JSON.stringify(r.tier)}`,
  r.distCode != null ? `distCode: ${r.distCode}` : null,
  r.courtCode != null ? `courtCode: ${r.courtCode}` : null,
  r.courtCodeArr != null ? `courtCodeArr: ${JSON.stringify(r.courtCodeArr)}` : null,
  r.estName != null ? `estName: ${JSON.stringify(r.estName)}` : null,
].filter(Boolean).join(", ") + " }";

const stateBlock = (code) =>
  `  ${code}: [\n${scopesByState[code].map((r) => "    " + rowLit(r) + ",").join("\n")}\n  ],`;

const out = `// GENERATED by scripts/gen-advocate-scopes.mjs — DO NOT EDIT BY HAND.
// Source of truth: the platform court-scope registry served at GET /v1/advocate-scopes?state_code=<int>
// (ecourts-scraper court.court_scope; BP-57). Per state:
${Object.values(provByState).map((p) => "//   • " + p).join("\n")}
// To widen district coverage: populate the PLATFORM registry (the gated masters walk) + re-run this
// generator — never hand-add a guessed complex here (info-integrity ⭐).
import type { BarSearchScope } from "./bar-number";

// One court scope keyed by eCourts numeric state_code. barSearchScopes zips these with a council's
// hcBarToken/dcBarToken (the search token stays sourced in bar-councils; geography lives here).
export type AdvocateScopeRow = Pick<BarSearchScope, "tier"> & {
  distCode?: number;
  courtCode?: number;
  courtCodeArr?: string;
  estName?: string;
};

export const ADVOCATE_SCOPES: Record<number, AdvocateScopeRow[]> = {
${Object.keys(scopesByState).map(stateBlock).join("\n")}
};

// Per-state coverage label (honest empty-state / UX): "full" (registry-populated) | "hc_only" |
// "hc_plus_one_complex" (the pre-W2 verified fallback). Drives never-a-false-zero messaging.
export const ADVOCATE_SCOPES_COVERAGE: Record<number, string> = {
${Object.entries(coverageByState).map(([c, cov]) => `  ${c}: ${JSON.stringify(cov)},`).join("\n")}
};
`;

writeFileSync(OUT, out);
console.log(`✓ ${OUT}`);
for (const p of Object.values(provByState)) console.log(`  ${p}`);
