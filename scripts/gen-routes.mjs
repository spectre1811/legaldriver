// WO-36 · Route inventory generator (zero-dependency — Node built-in fs.globSync).
// Globs every App-Router page and derives its URL path, so the E2E gate covers EVERY
// route automatically: a new `src/app/**/page.tsx` shows up here on the next run and is
// picked up by routes.spec.ts. No hand-maintained list to drift out of date.
//
// Run: node scripts/gen-routes.mjs  (or `npm run gen:routes`) → writes e2e/routes.generated.json
//
// Output shape: { generatedFrom, count, routes: [{ url, source, dynamic, params[], group }] }
//  - `dynamic` routes ([id], [...slug]) need a seeded id to visit → routes.spec seeds them
//    from E2E_ROUTE_IDS (see e2e/routes.spec.ts); un-seeded dynamic routes are skipped, not failed.

import { globSync } from "node:fs";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const APP_DIR = "src/app";

// Segments to drop from the URL: route groups (auth), parallel/intercepting slots (@modal, (.)).
const isRouteGroup = (seg) => /^\(.*\)$/.test(seg);
const isSlot = (seg) => seg.startsWith("@");
const isDynamic = (seg) => /^\[.*\]$/.test(seg);

function toRoute(relPath) {
  // relPath like "dashboard/cases/[id]/page.tsx" → segments without the page file.
  const segs = relPath.split("/").slice(0, -1); // drop page.tsx
  const params = [];
  let group = null;
  const urlSegs = [];
  for (const seg of segs) {
    if (isRouteGroup(seg)) { group = seg.slice(1, -1); continue; }
    if (isSlot(seg)) continue;
    if (isDynamic(seg)) {
      const name = seg.replace(/^\[+\.*/, "").replace(/\]+$/, ""); // [id] | [...barId] | [[...x]]
      params.push(name);
    }
    urlSegs.push(seg);
  }
  const url = "/" + urlSegs.join("/");
  return {
    url: url === "/" ? "/" : url.replace(/\/$/, ""),
    source: `${APP_DIR}/${relPath}`,
    dynamic: params.length > 0,
    params,
    group,
  };
}

const files = globSync(`${APP_DIR}/**/page.tsx`, { cwd: root }).sort();
// globSync returns paths WITH the src/app/ prefix — strip it so toRoute sees a page-relative path.
const routes = files.map((f) => toRoute(f.slice(APP_DIR.length + 1)));

const out = {
  generatedFrom: `${APP_DIR}/**/page.tsx`,
  note: "Auto-generated by scripts/gen-routes.mjs — do not edit by hand. Re-run `npm run gen:routes`.",
  count: routes.length,
  static: routes.filter((r) => !r.dynamic).length,
  dynamic: routes.filter((r) => r.dynamic).length,
  routes,
};

const dest = join(root, "e2e/routes.generated.json");
writeFileSync(dest, JSON.stringify(out, null, 2) + "\n");
console.log(`gen-routes: ${routes.length} routes (${out.static} static, ${out.dynamic} dynamic) → e2e/routes.generated.json`);
