#!/usr/bin/env node
// WO-46 Wave C / BP-05 W2 · Generate src/lib/court/bar-councils.data.ts.
//
// SOURCE OF TRUTH (design §2): the State Bar Council registry — the eCourts advocate-roster search
// tokens (`barstatecode`, numeric `state_code`) per council — is OWNED and SERVED by the platform at
// GET /v1/dictionaries?dims=bar_council (ecourts-scraper). This generator pulls that contract so the
// app's STATE_BAR_COUNCILS is a build-time-generated CONSUMER, never a hand-maintained copy that can
// drift from the platform (adding a state becomes a platform data row, not a code deploy here).
// It falls back to the committed snapshot (bar-councils.source.json) when the platform is unreachable
// (offline builds), so this never breaks a build. Output shape == the StateBarCouncil[] the runtime
// (bar-number.ts) and every call-site already expect — so nothing downstream changes.
//
// THREE DISTINCT ids (design §1, never conflated): contract `id` = eCourts 2-letter/CNR prefix (the
// <select> value) → StateBarCouncil.id; contract `alpha` = the enrolment letter ("G") → statePrefix;
// contract `hc_bar_token`/`dc_bar_token` = the `barstatecode` search param. Only `verified` councils
// carry tokens (Gujarat today); the rest stay null → honest name-fallback empty-state, never guessed.
//
// Run (contract, default): LD_API_BASE=http://13.202.148.71:8080 LD_API_KEY=… node scripts/gen-bar-councils.mjs
// Run (force offline):     node scripts/gen-bar-councils.mjs --source=json
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const SRC = join(root, "src/lib/court/bar-councils.source.json");
const OUT = join(root, "src/lib/court/bar-councils.data.ts");
const forceJson = process.argv.includes("--source=json");

// Map a platform-contract council record → the app's StateBarCouncil shape (drops the contract-only
// roster_scope/source the app doesn't consume yet; keeps the identity fields distinct).
const toCouncil = (r) => ({
  id: r.id,
  label: r.label,
  statePrefix: r.alpha ?? null,          // enrolment letter ("G"); distinct from id ("GJ") + token
  stateCode: r.ecourts_state_code ?? null,
  hcBarToken: r.hc_bar_token ?? null,
  dcBarToken: r.dc_bar_token ?? null,
  verified: !!r.verified,
});

// ── source: platform contract (BP-05 /v1/dictionaries?dims=bar_council) ──────
async function loadFromContract() {
  const base = process.env.LD_API_BASE, key = process.env.LD_API_KEY;
  if (!base || !key) return null;
  try {
    const res = await fetch(`${base.replace(/\/$/, "")}/v1/dictionaries?dims=bar_council`, {
      headers: { "X-API-Key": key }, signal: AbortSignal.timeout(30000),
    });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const body = await res.json();
    const councils = body?.dimensions?.bar_council?.councils;
    if (!Array.isArray(councils) || !councils.length) throw new Error("no bar_council.councils in contract response");
    return { councils, provenance: `the platform /v1/dictionaries?dims=bar_council contract (generated_at ${body.generated_at})` };
  } catch (e) {
    console.warn(`[gen-bar-councils] contract fetch failed (${e.message}); falling back to committed snapshot`);
    return null;
  }
}

// ── source: committed offline snapshot (fallback, mirror of the platform registry) ──
function loadFromJson() {
  const councils = JSON.parse(readFileSync(SRC, "utf8")).councils;
  return { councils, provenance: "the committed offline snapshot (bar-councils.source.json)" };
}

// ── emit ─────────────────────────────────────────────────────────────────────
const { councils, provenance } = (!forceJson && await loadFromContract()) || loadFromJson();
const mapped = councils.map(toCouncil);
const verified = mapped.filter((c) => c.verified);
// Invariant the runtime relies on (info-integrity): an unverified council must carry NO token.
for (const c of mapped) {
  if (!c.verified && (c.hcBarToken || c.dcBarToken || c.stateCode !== null || c.statePrefix !== null)) {
    throw new Error(`unverified council ${c.id} leaks a token/prefix — the registry is inconsistent`);
  }
}

const lit = (v) => (v === null ? "null" : JSON.stringify(v));
const row = (c) => `  { id: ${lit(c.id)}, label: ${lit(c.label)}, statePrefix: ${lit(c.statePrefix)}, `
  + `stateCode: ${lit(c.stateCode)}, hcBarToken: ${lit(c.hcBarToken)}, dcBarToken: ${lit(c.dcBarToken)}, `
  + `verified: ${c.verified} },`;

const out = `// GENERATED by scripts/gen-bar-councils.mjs — DO NOT EDIT BY HAND.
// Source of truth: ${provenance}. The State Bar Council registry (eCourts roster-search tokens) is
// owned + served by the platform (design §2); ${verified.length} of ${mapped.length} councils are
// packet-verified and carry a live search token — the rest stay null (honest name-fallback), never
// guessed. To add/verify a state: change the PLATFORM registry (ecourts-scraper
// scraper/bar_councils.source.json) + re-run this generator. Do not hand-edit tokens here.
import type { StateBarCouncil } from "./bar-number";

export const STATE_BAR_COUNCILS: StateBarCouncil[] = [
${mapped.map(row).join("\n")}
];
`;

writeFileSync(OUT, out);
console.log(`✓ ${OUT}`);
console.log(`  source: ${provenance}`);
console.log(`  councils: ${mapped.length}  ·  verified (live token): ${verified.length} (${verified.map((c) => c.id).join(", ")})`);
