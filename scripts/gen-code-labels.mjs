#!/usr/bin/env node
// WO-32 · Generate src/lib/court/code-labels.data.ts from the SOURCED corpus CSV.
//
// The eCourts corpus self-labels its own case-type expansions:
//   HIGH:     "CODE(FULL NAME)-NN"   e.g.  CR.A(CRIMINAL APPEAL)-43
//   DISTRICT: "CODE - Full Name"     e.g.  CC - CRIMINAL CASE
// We mine those labeled variants to learn each bare code's full name — so the master is
// derived from the data, never hand-guessed. Bare codes with no labeled sibling in the
// corpus are emitted to UNRESOLVED (surfaced in exec/DATA-GAPS.md) and stay raw in the UI.
//
// Run: node scripts/gen-code-labels.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const SRC = join(root, "src/lib/court/code-labels.source.csv");
const OUT = join(root, "src/lib/court/code-labels.data.ts");

// Normalize a case-type code so punctuation/spacing variants collapse:
//   "CRMA-S" / "CRMA S" -> "CRMA S";  "CR.MA" -> "CR MA";  "CMA-DC" -> "CMA DC".
const normCode = (c) => c.toUpperCase().replace(/[.\-\s]+/g, " ").trim();

// Extract [code, full] from a self-describing case_type string, or null if it's a bare code.
// District " - Full" is tried FIRST because district full-names can themselves end in
// "(...)" (e.g. "RECO33C2-LC - Recovery 33C (2)") which would fool the HC paren pattern.
function parseLabeled(raw) {
  const dc = raw.match(/^(.+?)\s-\s(.+)$/); // CODE - Full  (split on first " - ")
  if (dc) return [dc[1].trim(), dc[2].trim()];
  const hc = raw.match(/^([^()]+?)\((.+)\)(?:-\d+)?$/); // CODE(FULL)-NN — code has no parens
  if (hc) return [hc[1].trim(), hc[2].trim()];
  return null;
}

const rows = readFileSync(SRC, "utf8")
  .split("\n")
  .filter((l) => l && !l.startsWith("#") && !l.startsWith("tier,"))
  .map((l) => {
    const i = l.indexOf(","), j = l.lastIndexOf(",");
    return { tier: l.slice(0, i), raw: l.slice(i + 1, j), n: Number(l.slice(j + 1)) || 0 };
  })
  .filter((r) => r.raw);

// tier -> normKey -> { full, n } (keep the highest-count expansion when several disagree)
const master = { HIGH: {}, DISTRICT: {} };
const bare = { HIGH: new Map(), DISTRICT: new Map() }; // normKey -> {raw, n}

for (const { tier, raw, n } of rows) {
  const t = tier === "HIGH" ? "HIGH" : "DISTRICT";
  const parsed = parseLabeled(raw);
  if (parsed) {
    const key = normCode(parsed[0]);
    const prev = master[t][key];
    if (!prev || n > prev.n) master[t][key] = { full: parsed[1], n };
  } else {
    const key = normCode(raw);
    const prev = bare[t].get(key);
    if (!prev || n > prev.n) bare[t].set(key, { raw, n });
  }
}

// ANY fallback: for each key, prefer the highest-count expansion across tiers, so a missing
// tier still yields the dominant meaning (district "CC"=352k Criminal Case beats HC "CC"=3).
const anyMaster = {};
for (const t of ["HIGH", "DISTRICT"]) {
  for (const [key, v] of Object.entries(master[t])) {
    if (!anyMaster[key] || v.n > anyMaster[key].n) anyMaster[key] = v;
  }
}

// A bare code resolves if the same normalized key was labeled in EITHER tier.
const unresolved = [];
for (const t of ["HIGH", "DISTRICT"]) {
  for (const [key, { raw, n }] of bare[t]) {
    if (!master[t][key] && !anyMaster[key]) unresolved.push({ tier: t, code: raw, n });
  }
}
unresolved.sort((a, b) => b.n - a.n);

// Emit: per-tier maps + an ANY fallback (district ∪ high). Values are the corpus's own
// full text (uppercase); the runtime helper title-cases for display.
const emit = (m) =>
  "{ " + Object.keys(m).sort().map((k) => `${JSON.stringify(k)}: ${JSON.stringify(m[k].full)}`).join(", ") + " }";

const resolvedCount = new Set([...Object.keys(master.HIGH), ...Object.keys(master.DISTRICT)]).size;
const out = `// GENERATED by scripts/gen-code-labels.mjs from code-labels.source.csv — DO NOT EDIT BY HAND.
// Sourced from the live eCourts corpus (court.legal_case, 2026-07-05); the corpus self-labels
// its own case-type expansions. ${resolvedCount} codes resolved; ${unresolved.length} bare codes
// had no labeled sibling and stay raw (see UNRESOLVED_CASE_TYPES + exec/DATA-GAPS.md).

export const CASE_TYPE_MASTER: Record<string, Record<string, string>> = {
  HIGH: ${emit(master.HIGH)},
  DISTRICT: ${emit(master.DISTRICT)},
  ANY: ${emit(anyMaster)},
};

// Bare codes seen in the corpus with NO sourced expansion — shown raw + flagged, never guessed.
export const UNRESOLVED_CASE_TYPES: { tier: string; code: string; n: number }[] = [
${unresolved.map((u) => `  { tier: ${JSON.stringify(u.tier)}, code: ${JSON.stringify(u.code)}, n: ${u.n} },`).join("\n")}
];
`;

writeFileSync(OUT, out);
console.log(`✓ ${OUT}`);
console.log(`  resolved codes: ${resolvedCount}  ·  unresolved (stay raw): ${unresolved.length}`);
console.log(`  top unresolved: ${unresolved.slice(0, 12).map((u) => `${u.code}(${u.n})`).join(", ")}`);
