import type { Database } from "@/lib/db/database.types";

type Invoice = Database["public"]["Tables"]["invoice"]["Row"];
type Line = Database["public"]["Tables"]["invoice_line"]["Row"];
type Firm = Database["public"]["Tables"]["firm_billing"]["Row"];

const rupees = (minor: number) => `₹${(minor / 100).toLocaleString("en-IN", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
const esc = (s: string | null | undefined) => (s ?? "").replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]!));

// Self-contained HTML invoice (inline styles) — used both for the Resend email body
// and the printable /print view (browser "Save as PDF"). India GST format.
export function renderInvoiceHtml(opts: { invoice: Invoice; lines: Line[]; firm: Firm | null; clientName: string }): string {
  const { invoice: inv, lines, firm, clientName } = opts;
  const taxRow = (label: string, minor: number) => (minor > 0 ? `<tr><td colspan="4" style="text-align:right;padding:4px 8px">${label}</td><td style="text-align:right;padding:4px 8px">${rupees(minor)}</td></tr>` : "");
  const rcmNote = inv.reverse_charge ? `<p style="margin:8px 0;color:#92400e">Tax payable by recipient under Reverse Charge Mechanism (RCM). GST not charged on this invoice.</p>` : "";

  return `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Invoice ${esc(inv.number ?? "(draft)")}</title></head>
<body style="font-family:-apple-system,Segoe UI,Roboto,Arial,sans-serif;color:#1f2937;max-width:720px;margin:0 auto;padding:24px">
  <div style="display:flex;justify-content:space-between;align-items:flex-start;gap:16px">
    <div>
      <h1 style="font-size:20px;margin:0 0 4px">${esc(firm?.legal_name ?? "Tax Invoice")}</h1>
      <div style="font-size:12px;color:#6b7280;white-space:pre-line">${esc(firm?.address ?? "")}</div>
      ${firm?.gstin ? `<div style="font-size:12px;color:#6b7280">GSTIN: ${esc(firm.gstin)}${firm.state_code ? ` · State: ${esc(firm.state_code)}` : ""}</div>` : ""}
    </div>
    <div style="text-align:right">
      <div style="font-size:18px;font-weight:600">TAX INVOICE</div>
      <div style="font-size:13px">${esc(inv.number ?? "DRAFT")}</div>
      <div style="font-size:12px;color:#6b7280">Date: ${esc(inv.issue_date)}${inv.due_date ? ` · Due: ${esc(inv.due_date)}` : ""}</div>
      ${inv.fy ? `<div style="font-size:12px;color:#6b7280">FY ${esc(inv.fy)}</div>` : ""}
    </div>
  </div>
  <div style="margin:16px 0;font-size:13px"><strong>Bill to:</strong> ${esc(clientName)}${inv.place_of_supply ? ` · Place of supply: ${esc(inv.place_of_supply)}` : ""}</div>
  <table style="width:100%;border-collapse:collapse;font-size:13px">
    <thead><tr style="background:#f3f4f6">
      <th style="text-align:left;padding:6px 8px">Description</th>
      <th style="text-align:left;padding:6px 8px">SAC</th>
      <th style="text-align:right;padding:6px 8px">Qty</th>
      <th style="text-align:right;padding:6px 8px">Rate</th>
      <th style="text-align:right;padding:6px 8px">Amount</th>
    </tr></thead>
    <tbody>
      ${lines.map((l) => `<tr style="border-bottom:1px solid #e5e7eb">
        <td style="padding:6px 8px">${esc(l.description)}</td>
        <td style="padding:6px 8px">${esc(l.hsn_sac ?? "")}</td>
        <td style="text-align:right;padding:6px 8px">${l.quantity}${l.unit ? ` ${esc(l.unit)}` : ""}</td>
        <td style="text-align:right;padding:6px 8px">${rupees(l.rate_minor)}</td>
        <td style="text-align:right;padding:6px 8px">${rupees(l.amount_minor)}</td></tr>`).join("")}
    </tbody>
    <tfoot>
      <tr><td colspan="4" style="text-align:right;padding:4px 8px"><strong>Subtotal</strong></td><td style="text-align:right;padding:4px 8px">${rupees(inv.subtotal_minor)}</td></tr>
      ${taxRow(`CGST (${Number(inv.gst_rate) / 2}%)`, inv.cgst_minor)}
      ${taxRow(`SGST (${Number(inv.gst_rate) / 2}%)`, inv.sgst_minor)}
      ${taxRow(`IGST (${Number(inv.gst_rate)}%)`, inv.igst_minor)}
      <tr style="border-top:2px solid #1f2937"><td colspan="4" style="text-align:right;padding:8px"><strong>Total</strong></td><td style="text-align:right;padding:8px"><strong>${rupees(inv.total_minor)}</strong></td></tr>
    </tfoot>
  </table>
  ${rcmNote}
  ${firm?.bank_details ? `<div style="margin-top:16px;font-size:12px;color:#374151"><strong>Payment:</strong><div style="white-space:pre-line">${esc(firm.bank_details)}</div></div>` : ""}
  ${firm?.terms ? `<div style="margin-top:12px;font-size:11px;color:#6b7280;white-space:pre-line">${esc(firm.terms)}</div>` : ""}
  <p style="margin-top:20px;font-size:11px;color:#9ca3af">Generated by Legaldriver. This is a computer-generated tax invoice.</p>
</body></html>`;
}
